N=input("Enter the length of the input sequence");
K=input("Enter the length of DFT");
n=0:N-1;
k=0:K-1;
x=1.*sin(((2.*pi)/N).*n);
X=fft(x,K);
x1=ifft(X,N);
subplot(2,2,1);
stem(n, x);
xlabel('n');
ylabel('amplitude');
subplot(2,2,2);
stem(k, abs(X));
xlabel('discrete frequency');
ylabel('strength of kth harmonic of fundamental freq=2pi/M');subplot(2,2,2);
subplot(2,2,3);
stem(k, angle(X));
xlabel('discrete frequency');
ylabel('phase of kth harmonic of fundamental freq=2pi/M');
subplot(2,2,4);
stem(n, x1);
xlabel('n');
ylabel('x(n)');